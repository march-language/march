(* ── container ─────────────────────────────────────────────────────────── *)

let sh cmd = Sys.command cmd = 0

let capture cmd =
  let ic = Unix.open_process_in cmd in
  let s = In_channel.input_all ic in
  ignore (Unix.close_process_in ic);
  String.trim s

let skip reason =
  let bar = String.make 72 '*' in
  Printf.eprintf "\n%s\n* SKIP: forge host init container test: %s\n%s\n%!" bar reason bar;
  Alcotest.skip ()

let dockerfile = {|FROM alpine:3.21
RUN apk add --no-cache openssh-server && ssh-keygen -A && mkdir -p /root/.ssh && chmod 700 /root/.ssh \
 && sed -i 's/^#\?PermitRootLogin.*/PermitRootLogin prohibit-password/' /etc/ssh/sshd_config \
 && sed -i 's/^#\?AllowStreamLocalForwarding.*/AllowStreamLocalForwarding yes/' /etc/ssh/sshd_config \
 && passwd -u root 2>/dev/null || true
CMD ["/usr/sbin/sshd", "-D", "-e"]
|}

let image = "forge-host-init-test:1"

let test_container_idempotent () =
  if not (sh "command -v docker >/dev/null 2>&1") then skip "docker is not installed";
  if not (sh "docker info >/dev/null 2>&1") then skip "docker is installed but its daemon is not reachable";
  if not (sh "command -v ssh >/dev/null 2>&1 && command -v ssh-keygen >/dev/null 2>&1") then skip "no ssh client";
  with_home @@ fun () ->
  let dir = short_tmp "c" in
  let ctx = Filename.concat dir "image" in
  mkdir_p ctx;
  write_file (Filename.concat ctx "Dockerfile") dockerfile;
  if not (sh (Printf.sprintf "docker build -q -t %s %s >%s/build.log 2>&1" image ctx dir)) then
    skip (Printf.sprintf "the sshd image did not build (no network?): %s" (read_file (Filename.concat dir "build.log")));
  let key = Filename.concat dir "id_ed25519" in
  if not (sh (Printf.sprintf "ssh-keygen -q -t ed25519 -N '' -f %s" key)) then Alcotest.fail "ssh-keygen";
  let name = Printf.sprintf "forge-host-init-%d" (Unix.getpid ()) in
  if not (sh (Printf.sprintf "docker run -d --name %s -p 127.0.0.1::22 %s >/dev/null" name image)) then
    Alcotest.fail "docker run";
  Fun.protect ~finally:(fun () -> ignore (sh (Printf.sprintf "docker rm -f %s >/dev/null 2>&1" name))) @@ fun () ->
  if not (sh (Printf.sprintf "docker cp %s.pub %s:/root/.ssh/authorized_keys && docker exec %s chown root:root /root/.ssh/authorized_keys"
                key name name)) then Alcotest.fail "installing the key";
  let port = capture (Printf.sprintf "docker port %s 22/tcp | head -1 | sed 's/.*://'" name) in
  let cfg = Filename.concat dir "ssh_config" in
  write_file cfg (Printf.sprintf
                    "Host web-1 web-2\n  HostName 127.0.0.1\n  Port %s\n  User root\n  IdentityFile %s\n\
                    \  IdentitiesOnly yes\n  StrictHostKeyChecking no\n  UserKnownHostsFile /dev/null\n  LogLevel ERROR\n"
                    port key);
  Unix.putenv "FORGE_SSH_CONFIG" cfg;
  Fun.protect ~finally:(fun () -> Unix.putenv "FORGE_SSH_CONFIG" "") @@ fun () ->
  (* sshd needs a moment after the container starts. *)
  let rec wait n =
    if sh (Printf.sprintf "ssh -F %s web-1 true >/dev/null 2>&1" cfg) then ()
    else if n = 0 then Alcotest.fail "sshd in the container never answered"
    else (Unix.sleepf 0.5; wait (n - 1))
  in
  wait 40;
  (* Both pools' hosts are the one container: a two-pool cluster on one
     machine is refused by the ssh backend, so give pool b no hosts here. *)
  let proj = make_project ~dir ~host_a:"root@web-1" ~host_b:"root@web-1" in
  write_file (Filename.concat proj.Project.root "topology.prod.toml")
    "[pool.a]\nhosts = [{ host = \"root@web-1\", labels = [\"edge\"] }]\n\n[backend]\nkind = \"ssh\"\n";
  let run () = Host_init.run ~proj ~opts () in
  let first = match run () with Ok r -> r | Error m -> Alcotest.failf "first run over ssh failed:\n%s" m in
  print_string first;
  expect "first run" first [ "changed (user march"; "/etc/systemd/system/march-a.service";
                             "note: ufw is not installed" ];
  let exec c = capture (Printf.sprintf "docker exec %s sh -c %s" name (Filename.quote c)) in
  Alcotest.(check string) "the march user" "march" (exec "id -un march");
  Alcotest.(check string) "state dir owner and mode" "march:march 750" (exec "stat -c '%U:%G %a' /var/lib/march/app");
  Alcotest.(check string) "env file owner and mode" "root:march 640" (exec "stat -c '%U:%G %a' /etc/march/app/a.env");
  expect "unit in the container" (exec "cat /etc/systemd/system/march-a.service")
    [ "Environment=MARCH_NODE_NAME=a-web-1"; "Environment=MARCH_DEPLOY_POLICY=/etc/march/app/a.policy"; "User=march" ];
  Alcotest.(check string) "policy" "IO.Console" (exec "cat /etc/march/app/a.policy");
  let arch = exec "uname -m" in
  (match Reconcile.read_host_records ~root:proj.Project.root (Some "prod") with
   | Ok [ r ] ->
     Alcotest.(check string) "recorded target"
       (if arch = "x86_64" then "linux/amd64" else "linux/arm64") r.Reconcile.hr_target;
     Alcotest.(check string) "recorded triple"
       (if arch = "x86_64" then "x86_64-unknown-linux-gnu" else "aarch64-unknown-linux-gnu") r.hr_triple
   | Ok rs -> Alcotest.failf "expected one record, got %d" (List.length rs)
   | Error m -> Alcotest.fail m);
  let second = match run () with Ok r -> r | Error m -> Alcotest.failf "second run over ssh failed:\n%s" m in
  print_string second;
  expect "second run" second [ "a-web-1 (root@web-1, pool a): no change" ];
  refuse "second run" second [ "changed (" ]

let () =
  (* Said before Alcotest captures the test's output, so a skipped
     acceptance test is visible in the console, not only in its log. *)
  if not (sh "command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1") then begin
    let bar = String.make 72 '*' in
    Printf.eprintf "%s\n* SKIP: the forge host init CONTAINER test will be skipped: Docker is absent or its\n\
                    * daemon is not reachable. The acceptance (idempotent against a container host)\n\
                    * is NOT exercised by this run.\n%s\n%!" bar bar
  end;
  Alcotest.run "host-init" [
    ("local", [
        Alcotest.test_case "files, environment, secret and certificate modes; a second run changes nothing" `Quick
          test_local_idempotent;
        Alcotest.test_case "refuses a topology that is not ssh" `Quick test_refuses_non_ssh;
      ]);
    ("container", [
        Alcotest.test_case "over ssh against an sshd container: converges, records the target, idempotent" `Slow
          test_container_idempotent;
      ]);
  ]
