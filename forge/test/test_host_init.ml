(** [forge host init] (distributed-deploys build step 10b, item 2).

    - [local]: the host script run by this machine's [sh] against a
      scratch directory ([Host_layout] relocated under a prefix, no user
      creation, no chown): the files and the environment the unit gets, the
      shared-secret and certificate modes, and idempotence (a second run
      changes nothing).
    - [container]: the acceptance: the real thing over ssh against a
      Docker container running sshd (alpine), as root: the march user, the
      directories, the files with their owners and modes, the recorded
      target, and a second run that changes nothing. Skipped, loudly, when
      Docker is absent or cannot build the image; never a vacuous pass. *)

open March_forge

let contains s sub =
  let n = String.length s and k = String.length sub in
  let rec go i = i + k <= n && (String.sub s i k = sub || go (i + 1)) in
  go 0

let read_file path = try In_channel.with_open_bin path In_channel.input_all with Sys_error _ -> ""
let write_file path s = Out_channel.with_open_bin path (fun oc -> output_string oc s)
let rec mkdir_p d = if not (Sys.file_exists d) then (mkdir_p (Filename.dirname d); Unix.mkdir d 0o755)

let short_tmp tag =
  let d = Printf.sprintf "/tmp/fhi%s%d_%d" tag (Unix.getpid ()) (Random.int 100000) in
  Unix.mkdir d 0o755; d

let expect what text subs =
  List.iter (fun s -> if not (contains text s) then Alcotest.failf "%s: expected %S in:\n%s" what s text) subs

let refuse what text subs =
  List.iter (fun s -> if contains text s then Alcotest.failf "%s: did not expect %S in:\n%s" what s text) subs

(** A two-pool ssh project under [dir]/proj, its deploy key in [dir]/home.
    [hosts]: the overlay's host of pool a and of pool b. *)
let make_project ~dir ~host_a ~host_b =
  let root = Filename.concat dir "proj" in
  mkdir_p (Filename.concat root "src");
  write_file (Filename.concat root "forge.toml") "[package]\nname = \"app\"\nversion = \"0.1.0\"\n";
  write_file (Filename.concat root "src/app.march")
    "mod App do\n  protocol Echo do\n    ask: Client -> Server : Int\n    answer: Server -> Client : Int\n  end\n\
    \  fn serve(x) do x end\nend\n";
  write_file (Filename.concat root "topology.toml")
    "[roles]\n\"Echo.Server\" = { body = \"App.serve\" }\n\n\
     [pool.a]\nserves = [\"Echo.Server\"]\ncaps = [\"IO.Console\"]\npublic = [8080]\n\n\
     [pool.b]\nserves = [\"Echo.Server\"]\ninitiates = [\"Echo.Client\"]\ncaps = []\n";
  write_file (Filename.concat root "topology.prod.toml")
    (Printf.sprintf "[pool.a]\nhosts = [{ host = %S, labels = [\"edge\"] }]\n\n[pool.b]\nhosts = [%S]\n\n\
                     [backend]\nkind = \"ssh\"\n" host_a host_b);
  let home = Filename.concat dir "home" in
  mkdir_p home;
  Unix.putenv "HOME" home;
  let (_, sk) = March_ed25519.Ed25519.keygen () in
  (match Cmd_hot_reload.save_sk sk with Ok () -> () | Error m -> Alcotest.fail m);
  match Project.load_from_dir root with
  | Ok p -> p
  | Error m -> Alcotest.fail m

let with_home f =
  let old = Sys.getenv_opt "HOME" in
  Fun.protect ~finally:(fun () -> Option.iter (Unix.putenv "HOME") old) f

let opts = Host_init.default_opts (Some "prod")

(* ── local ─────────────────────────────────────────────────────────────── *)

let test_local_idempotent () =
  with_home @@ fun () ->
  let dir = short_tmp "l" in
  let proj = make_project ~dir ~host_a:"root@web-1" ~host_b:"root@web-2" in
  let root = proj.Project.root in
  let prefix = Filename.concat dir "host" in
  mkdir_p prefix;
  let run () = Host_init.run ~transport:Remote.local ~service_ctl:"false" ~layout_prefix:prefix ~proj ~opts () in
  let first = match run () with Ok r -> r | Error m -> Alcotest.failf "first run failed:\n%s" m in
  expect "first run" first [ "2 host(s), shared-secret mode"; "a-web-1 (root@web-1, pool a): "; "changed (";
                             "note: systemd is not running here: march-a.service was written, not enabled" ];
  let layout = Host_layout.make ~prefix "app" in
  let unit_a = read_file (Host_layout.unit_file layout "a") in
  expect "unit a" unit_a
    [ "User=march"; "ExecStart=/opt/march/app/app"; "Environment=MARCH_POOLS=a"; "Environment=MARCH_NODE_NAME=a-web-1";
      "Environment=MARCH_NODE_PORT=7946"; "Environment=MARCH_NODE_ADVERTISE=web-1:7946";
      "Environment=MARCH_CLUSTER_NODES=web-2:7946"; "Environment=MARCH_NODE_LABELS=edge";
      "Environment=MARCH_TOPOLOGY_FILE=/etc/march/app/topology.json";
      "Environment=MARCH_TOPOLOGY_STATUS=/var/lib/march/app/run/a.status";
      "Environment=MARCH_HOT_RELOAD_SOCKET=/var/lib/march/app/run/a.sock";
      "Environment=MARCH_DEPLOY_POLICY=/etc/march/app/a.policy"; "Environment=HOME=/var/lib/march/app";
      "EnvironmentFile=-/etc/march/app/a.env"; "generated by `forge host init`" ];
  refuse "unit a (secrets stay out of the world-readable unit)" unit_a [ "MARCH_CLUSTER_SECRET"; "MARCH_NODE_CERT" ];
  let secret = String.trim (read_file (Filename.concat root ".forge/hosts/prod/cluster.secret")) in
  Alcotest.(check int) "a 32-byte secret" 64 (String.length secret);
  Alcotest.(check string) "env file" ("MARCH_CLUSTER_SECRET=" ^ secret ^ "\n") (read_file (Host_layout.env_file layout "a"));
  Alcotest.(check int) "env file mode" 0o640 ((Unix.stat (Host_layout.env_file layout "a")).Unix.st_perm);
  Alcotest.(check string) "policy a: the written caps" "IO.Console\n" (read_file (Host_layout.policy_file layout "a"));
  Alcotest.(check string) "policy b: caps = [] allows nothing" "" (read_file (Host_layout.policy_file layout "b"));
  expect "firewall a" (read_file (Host_layout.firewall_file layout "a"))
    [ "ufw allow 22/tcp"; "ufw allow 8080/tcp"; "ufw allow from web-2 to any port 7946" ];
  Alcotest.(check bool) "deploy.pub" true (String.length (read_file (Host_layout.deploy_pub layout)) > 40);
  expect "topology" (read_file (Host_layout.topology_file layout)) [ "\"version\": 1"; "\"Echo.Server\"" ];
  expect "do-firewall written locally" (read_file (Filename.concat root ".forge/hosts/prod/do-firewalls.json"))
    [ "march-a"; "8080" ];
  (match Reconcile.read_host_records ~root (Some "prod") with
   | Ok [ a; b ] ->
     Alcotest.(check string) "node" "a-web-1" a.Reconcile.hr_node;
     Alcotest.(check string) "pool" "b" b.Reconcile.hr_pool;
     Alcotest.(check bool) ("target from uname: " ^ a.hr_uname ^ " -> " ^ a.hr_target) true
       (a.hr_target = "darwin/arm64" || a.hr_target = "darwin/amd64" || a.hr_target = "linux/amd64"
        || a.hr_target = "linux/arm64")
   | Ok rs -> Alcotest.failf "expected 2 records, got %d" (List.length rs)
   | Error m -> Alcotest.fail m);
  let second = match run () with Ok r -> r | Error m -> Alcotest.failf "second run failed:\n%s" m in
  expect "second run" second [ "a-web-1 (root@web-1, pool a): no change"; "b-web-2 (root@web-2, pool b): no change" ];
  refuse "second run" second [ "changed (" ];
  (* Certificate mode (step 11a): an operator key in .forge/cluster. *)
  (match Cmd_cluster.run_keygen ~out_dir:(let d = Filename.concat root ".forge/cluster" in mkdir_p d; d) ~force:false () with
   | Ok _ -> () | Error m -> Alcotest.fail m);
  let third = match run () with Ok r -> r | Error m -> Alcotest.failf "certificate run failed:\n%s" m in
  expect "certificate run" third [ "certificate mode"; "certs/a-web-1.cert"; "a.env" ];
  let unit_a = read_file (Host_layout.unit_file layout "a") in
  expect "unit a in certificate mode" unit_a
    [ "Environment=MARCH_NODE_CERT=/etc/march/app/certs/a-web-1.cert";
      "Environment=MARCH_NODE_KEY=/etc/march/app/certs/a-web-1.key";
      "Environment=MARCH_CLUSTER_OPERATOR_PUBKEY=/etc/march/app/certs/operator.pub" ];
  refuse "env file in certificate mode" (read_file (Host_layout.env_file layout "a")) [ "MARCH_CLUSTER_SECRET" ];
  Alcotest.(check string) "operator.pub is the operator's"
    (String.trim (read_file (Filename.concat root ".forge/cluster/operator.pub")))
    (String.trim (read_file (Host_layout.operator_pub layout)));
  let fourth = match run () with Ok r -> r | Error m -> Alcotest.failf "fourth run failed:\n%s" m in
  refuse "certificates are reused" fourth [ "changed (" ]

let test_refuses_non_ssh () =
  with_home @@ fun () ->
  let dir = short_tmp "n" in
  let proj = make_project ~dir ~host_a:"root@web-1" ~host_b:"root@web-2" in
  write_file (Filename.concat proj.Project.root "topology.prod.toml") "[pool.a]\nhosts = [\"root@web-1\"]\n";
