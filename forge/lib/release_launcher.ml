(** The generated [bin/<app>] launcher of a release bundle (R9 of
    specs/plans/2026-09-28-observe-recon-shell-plan.md, design section 7.2).

    A POSIX [sh] script, March-free: it runs on a host that has nothing but the
    unpacked bundle.  What the host needs:

    - always: [sh], [kill], [ls], [awk], [id], [sed], [grep], [cat], [mv], [mkdir]
      (any POSIX userland);
    - [ping], [version], [status] and the readiness wait of [daemon] talk to the
      node's observe socket, so they need ONE of [nc -U] (netcat with unix
      socket support, the default on macOS and Debian/Ubuntu's
      netcat-openbsd), [socat], or [python3].  Without any of them the verbs
      say so and exit 1; [start], [daemon], [stop], [pid] still work.

    Signing is not possible in [sh], so a drained stop is
    [forge deploy --drain] from an operator machine; [stop] here is SIGTERM,
    then SIGKILL after [MARCH_STOP_GRACE] seconds (the topology's soft drain
    deadline, written to [etc/env] by [forge release build]).

    The script never [eval]s anything it reads, quotes every expansion, and
    refuses to start, stop or restart as a user other than the owner of the
    release directory. *)

let valid_app_name (s : string) : bool =
  s <> ""
  && String.for_all
       (fun c ->
          (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
          || (c >= '0' && c <= '9') || c = '_' || c = '-' || c = '.')
       s
  && s.[0] <> '-' && s.[0] <> '.'

let template = {sh|#!/bin/sh
# bin/@APP@: the launcher of this release (generated by `forge release build`).
# POSIX sh, March-free. Verbs: start daemon stop restart pid version ping
# status eval rpc shell observe diagnose. `bin/@APP@ help` says what each does.
set -eu
umask 077

APP='@APP@'

die() {
  printf '%s: %s\n' "$APP" "$*" >&2
  exit 1
}

# Where this release lives: follow symlinks to the script, then up one level.
self=$0
while [ -L "$self" ]; do
  link=$(readlink "$self")
  case $link in
    /*) self=$link ;;
    *) self=$(dirname "$self")/$link ;;
  esac
done
ROOT=$(cd "$(dirname "$self")/.." && pwd -P) || die "cannot resolve the release directory"
BIN=$ROOT/lib/$APP

# etc/env: NAME=VALUE lines, applied to names the environment does not already
# set (so systemd's Environment= and an operator's export win). The file is
# read as data: no expansion, no quoting rules beyond one pair of surrounding
# quotes, and "@ROOT@" is the release directory.
load_env() {
  [ -r "$ROOT/etc/env" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    case $line in
      '' | '#'*) continue ;;
    esac
    key=${line%%=*}
    [ "$key" != "$line" ] || die "etc/env: not NAME=VALUE: $line"
    val=${line#*=}
    case $key in
      '' | [!A-Z_]* | *[!A-Z0-9_]*) die "etc/env: bad variable name: $key" ;;
    esac
    case $val in
      \"*\") val=${val#\"}; val=${val%\"} ;;
      \'*\') val=${val#\'}; val=${val%\'} ;;
    esac
    while :; do
      case $val in
        *'@ROOT@'*) val=${val%%'@ROOT@'*}$ROOT${val#*'@ROOT@'} ;;
        *) break ;;
      esac
    done
    if ! printenv "$key" >/dev/null 2>&1; then
      export "$key=$val"
    fi
  done <"$ROOT/etc/env"
}

# Paths, from etc/env and the environment. The reload socket is
# $RUN/<app>.sock and the observe socket beside it (<reload socket>.observe),
# the same pair `forge deploy hot` / `forge observe` use for a [hot-reload] host.
prepare() {
  load_env
  RUN=${MARCH_RUN_DIR:-$ROOT/run}
  LOG=${MARCH_LOG_DIR:-$ROOT/log}
  PIDFILE=$RUN/$APP.pid
  RELOAD_SOCK=$RUN/$APP.sock
  if [ -n "${MARCH_OBSERVE_SOCKET:-}" ]; then
    OBS=$MARCH_OBSERVE_SOCKET
  elif [ -n "${MARCH_HOT_RELOAD_SOCKET:-}" ]; then
    RELOAD_SOCK=$MARCH_HOT_RELOAD_SOCKET
    OBS=$MARCH_HOT_RELOAD_SOCKET.observe
  else
    OBS=$RELOAD_SOCK.observe
  fi
}

# Environment of the node itself (start / daemon).
node_env() {
  mkdir -p "$RUN" "$LOG"
  if [ -z "${MARCH_OBSERVE_SOCKET:-}" ] && [ -z "${MARCH_HOT_RELOAD_SOCKET:-}" ]; then
    if grep -q '^hot_reload=true$' "$ROOT/RELEASE" 2>/dev/null; then
      export MARCH_HOT_RELOAD_SOCKET="$RELOAD_SOCK"
    else
      export MARCH_OBSERVE_SOCKET="$OBS"
    fi
  fi
  if [ -z "${MARCH_AUDIT_LOG:-}" ]; then
    export MARCH_AUDIT_LOG="$RUN/audit.jsonl"
  fi
  # A Unix socket path is limited to 103 bytes (macOS) / 107 (Linux).
  if [ "${#OBS}" -gt 100 ]; then
    die "the observe socket path is too long (${#OBS} bytes): $OBS (set MARCH_RUN_DIR to a shorter directory)"
  fi
  if [ ! -x "$BIN" ]; then
    die "$BIN is not an executable file"
  fi
}

# Refuse to run as a surprise user: the node's files and sockets belong to the
# user that owns this release directory.
check_user() {
  me=$(id -u)
  # shellcheck disable=SC2012
  owner=$(ls -ldn "$ROOT" | awk '{print $3}')
  if [ "$me" != "$owner" ] && [ "${MARCH_ALLOW_ANY_USER:-}" != 1 ]; then
    die "refusing to run as uid $me: $ROOT is owned by uid $owner (run as that user, or set MARCH_ALLOW_ANY_USER=1)"
  fi
}

# The pid in the pidfile, if that process is alive (and is this app's binary
# when `ps` can tell).
live_pid() {
  [ -r "$PIDFILE" ] || return 1
  pid=$(cat "$PIDFILE" 2>/dev/null) || return 1
  case $pid in
    '' | *[!0-9]*) return 1 ;;
  esac
  kill -0 "$pid" 2>/dev/null || return 1
  cmd=$(ps -p "$pid" -o args= 2>/dev/null || true)
  case $cmd in
    '' | *"$APP"*) ;;
    *) return 1 ;;
  esac
  printf '%s\n' "$pid"
}

write_pid() {
  tmp=$PIDFILE.$$
  printf '%s\n' "$1" >"$tmp"
  mv -f "$tmp" "$PIDFILE"
}

# ask 'LINE': one request to the observe socket, the one-line reply on stdout.
# Tries nc -U, then socat, then python3; fails if the socket or all tools are
# missing.
ask() {
  [ -S "$OBS" ] || return 1
  if command -v nc >/dev/null 2>&1; then
    out=$(printf '%s\n' "$1" | nc -U -w 3 "$OBS" 2>/dev/null || true)
    if [ -n "$out" ]; then
      printf '%s\n' "$out"
      return 0
    fi
  fi
  if command -v socat >/dev/null 2>&1; then
    out=$(printf '%s\n' "$1" | socat -t 3 - "UNIX-CONNECT:$OBS" 2>/dev/null || true)
    if [ -n "$out" ]; then
      printf '%s\n' "$out"
      return 0
    fi
  fi
  if command -v python3 >/dev/null 2>&1; then
    out=$(python3 -c '
import socket, sys
s = socket.socket(socket.AF_UNIX)
s.settimeout(3)
s.connect(sys.argv[1])
s.sendall((sys.argv[2] + "\n").encode())
d = b""
while True:
    c = s.recv(65536)
    if not c:
        break
    d += c
sys.stdout.write(d.decode())
' "$OBS" "$1" 2>/dev/null || true)
    if [ -n "$out" ]; then
      printf '%s\n' "$out"
      return 0
    fi
  fi
  return 1
}

no_ask_hint() {
  if ! live_pid >/dev/null; then
    printf '%s: not running\n' "$APP" >&2
  elif [ ! -S "$OBS" ]; then
    printf '%s: no observe socket at %s yet\n' "$APP" "$OBS" >&2
  else
    printf '%s: cannot talk to %s: need nc (with -U), socat or python3 on this host\n' "$APP" "$OBS" >&2
  fi
}

nap() {
  sleep 0.2 2>/dev/null || sleep 1
}

cmd_start() {
  check_user
  prepare
  node_env
  if pid=$(live_pid); then
    die "already running (pid $pid)"
  fi
  write_pid "$$"
  exec "$BIN" "$@"
}

cmd_daemon() {
  check_user
  prepare
  node_env
  if pid=$(live_pid); then
    die "already running (pid $pid)"
  fi
  (
    trap '' HUP
    exec "$BIN" "$@"
  ) >>"$LOG/$APP.out" 2>&1 </dev/null &
  pid=$!
  write_pid "$pid"
  deadline=$(($(date +%s) + ${MARCH_START_TIMEOUT:-10}))
  while [ "$(date +%s)" -lt "$deadline" ]; do
    kill -0 "$pid" 2>/dev/null || die "exited while starting; see $LOG/$APP.out"
    if reply=$(ask PING) && case $reply in *'"pong"'*) true ;; *) false ;; esac; then
      printf 'started pid %s\n' "$pid"
      return 0
    fi
    nap
  done
  if kill -0 "$pid" 2>/dev/null; then
    printf '%s: started pid %s, but the observe socket %s did not answer within %ss\n' \
      "$APP" "$pid" "$OBS" "${MARCH_START_TIMEOUT:-10}" >&2
    return 0
  fi
  die "exited while starting; see $LOG/$APP.out"
}

# SIGTERM, then SIGKILL after MARCH_STOP_GRACE seconds (default: the topology's
# soft drain deadline from etc/env, else 30). A drained stop is
# `forge deploy --drain`: it needs the deploy key, which sh cannot sign with.
cmd_stop() {
  check_user
  prepare
  if ! pid=$(live_pid); then
    rm -f "$PIDFILE" "$RELOAD_SOCK" "$RELOAD_SOCK.shell" "$OBS"
    printf 'not running\n'
    return 0
  fi
  grace=${MARCH_STOP_GRACE:-30}
  case $grace in
    '' | *[!0-9]*) die "MARCH_STOP_GRACE must be a number of seconds, got: $grace" ;;
  esac
  kill -TERM "$pid" 2>/dev/null || true
  deadline=$(($(date +%s) + grace))
  while kill -0 "$pid" 2>/dev/null; do
    if [ "$(date +%s)" -ge "$deadline" ]; then
      printf '%s: pid %s still running after %ss; SIGKILL\n' "$APP" "$pid" "$grace" >&2
      kill -KILL "$pid" 2>/dev/null || true
      kill_deadline=$(($(date +%s) + 5))
      while kill -0 "$pid" 2>/dev/null && [ "$(date +%s)" -lt "$kill_deadline" ]; do
        nap
      done
      break
    fi
    nap
  done
  if kill -0 "$pid" 2>/dev/null; then
    die "pid $pid did not exit"
  fi
  rm -f "$PIDFILE" "$RELOAD_SOCK" "$RELOAD_SOCK.shell" "$OBS"
  printf 'stopped pid %s\n' "$pid"
}

cmd_restart() {
  cmd_stop
  cmd_daemon "$@"
}

cmd_pid() {
  prepare
  if pid=$(live_pid); then
    printf '%s\n' "$pid"
  else
    printf 'not running\n' >&2
    exit 1
  fi
}

cmd_ping() {
  prepare
  if reply=$(ask PING); then
    case $reply in
      *'"pong"'*) printf 'pong\n'; return 0 ;;
    esac
    printf '%s: unexpected reply: %s\n' "$APP" "$reply" >&2
    return 1
  fi
  no_ask_hint
  return 1
}

# The code epoch of the running node, from EPOCHS ({"data":{"current":N,...).
epoch_of() {
  reply=$(ask EPOCHS) || return 1
  printf '%s\n' "$reply" | sed -n 's/.*"data":{"current":\([0-9][0-9]*\).*/\1/p'
}

cmd_version() {
  prepare
  cat "$ROOT/RELEASE"
  if pid=$(live_pid); then
    printf 'running=pid %s\n' "$pid"
    if epoch=$(epoch_of) && [ -n "$epoch" ]; then
      printf 'epoch=%s\n' "$epoch"
    fi
  else
    printf 'running=no\n'
  fi
}

# `forge status` for this one node, without forge: the pid, then the node's own
# EPOCHS and MEM replies, one JSON line each.
cmd_status() {
  prepare
  if pid=$(live_pid); then
    printf 'running pid %s\n' "$pid"
  else
    printf 'not running\n'
    return 1
  fi
  for verb in EPOCHS MEM; do
    if reply=$(ask "$verb"); then
      printf '%s %s\n' "$verb" "$reply"
    else
      no_ask_hint
      return 1
    fi
  done
}

# rpc / shell / observe / diagnose need a forge that can reach the node: run it
# when it is on this host, else say which command to run elsewhere.
forge_verb() {
  verb=$1
  shift
  prepare
  case $verb in
    rpc | shell) sock=$RELOAD_SOCK ;;
    *) sock=$OBS ;;
  esac
  if command -v forge >/dev/null 2>&1; then
    exec forge "$verb" --socket "$sock" "$@"
  fi
  printf '%s: forge is not installed on this host. From a machine with forge and this project, run:\n' "$APP" >&2
  printf '  forge %s --env <env>   (over ssh to this host)\n' "$verb" >&2
  printf 'or, on this host once forge is installed:\n  forge %s --socket %s\n' "$verb" "$sock" >&2
  exit 3
}

cmd_eval() {
  printf '%s: eval needs a fresh march process on this bundle, which this release does not ship.\n' "$APP" >&2
  printf 'Use forge rpc against the running node instead.\n' >&2
  exit 3
}

usage() {
  cat <<'EOF_USAGE'
usage: bin/@APP@ <verb> [args]

  start [args]    run the node in the foreground (env from etc/env)
  daemon [args]   start detached; pid in run/, output in log/
  stop            SIGTERM, then SIGKILL after MARCH_STOP_GRACE seconds
                  (a drained stop is `forge deploy --drain`)
  restart         stop, then daemon
  pid             the node's pid (exit 1 if not running)
  version         RELEASE, and the node's epoch if it is running
  ping            ask the observe socket (needs nc -U, socat or python3)
  status          pid, EPOCHS and MEM replies of this node
  eval EXPR       not available in this release (see the message)
  rpc | shell | observe | diagnose
                  run `forge <verb> --socket ...` when forge is installed,
                  else print what to run

environment: MARCH_RUN_DIR (default run/), MARCH_LOG_DIR (log/),
MARCH_STOP_GRACE, MARCH_START_TIMEOUT, MARCH_ALLOW_ANY_USER; every MARCH_*
name in etc/env that the environment does not set.
EOF_USAGE
}

verb=${1:-help}
if [ "$#" -gt 0 ]; then shift; fi
case $verb in
  start) cmd_start "$@" ;;
  daemon) cmd_daemon "$@" ;;
  stop) cmd_stop ;;
  restart) cmd_restart "$@" ;;
  pid) cmd_pid ;;
  version) cmd_version ;;
  ping) cmd_ping ;;
  status) cmd_status ;;
  eval) cmd_eval ;;
  rpc | shell | observe | diagnose) forge_verb "$verb" "$@" ;;
  help | -h | --help) usage ;;
  *) usage >&2; exit 2 ;;
esac
|sh}

let script ~(app : string) : string =
  if not (valid_app_name app) then
    invalid_arg ("Release_launcher.script: bad app name " ^ app);
  let pat = "@APP@" in
  let b = Buffer.create (String.length template + 64) in
  let n = String.length template and k = String.length pat in
  let rec go i =
    if i >= n then ()
    else if i + k <= n && String.sub template i k = pat then (Buffer.add_string b app; go (i + k))
    else (Buffer.add_char b template.[i]; go (i + 1))
  in
  go 0;
  Buffer.contents b
