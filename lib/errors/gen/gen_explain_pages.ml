(* gen_explain_pages FILE... : print an OCaml module embedding each
   specs/lang/errors/<slug>.md page, keyed by its slug (the file's basename),
   with the Jekyll front matter stripped. Output is sorted by slug so the
   generated module is byte-stable whatever order dune passes the files in. *)

let read_file path =
  let ic = open_in_bin path in
  let n = in_channel_length ic in
  let s = really_input_string ic n in
  close_in ic;
  s

let strip_front_matter s =
  let lines = String.split_on_char '\n' s in
  match lines with
  | "---" :: rest ->
    let rec drop = function
      | [] -> []
      | "---" :: body -> body
      | _ :: tl -> drop tl
    in
    let rec trim_blank = function "" :: tl -> trim_blank tl | l -> l in
    String.concat "\n" (trim_blank (drop rest))
  | _ -> s

let () =
  let files = List.tl (Array.to_list Sys.argv) in
  let pages =
    files
    |> List.filter (fun f -> Filename.check_suffix f ".md")
    |> List.map (fun f ->
        (Filename.remove_extension (Filename.basename f),
         strip_front_matter (read_file f)))
    |> List.sort compare
  in
  print_string "(* GENERATED by lib/errors/gen/gen_explain_pages.ml from \
                specs/lang/errors/*.md. Do not edit. *)\n\n";
  print_string "let pages : (string * string) list = [\n";
  List.iter (fun (slug, body) ->
      if String.length body > 0 then
        Printf.printf "  (%S,\n   {march_page|%s|march_page});\n" slug body)
    pages;
  print_string "]\n"
