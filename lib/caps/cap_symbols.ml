   Each entry needs a justification; the freshness test fails on any
   cap-table builtin that is neither joinable into [table] nor listed here.
   - task_spawn_link: no llvm lowering exists (interpreter/actor-runtime
     path only; nothing to observe in a native binary).
   - get_work_pool:   lowers to a pool-handle global access
     (llvm_emit.ml:369), not a call — no symbol is referenced.
