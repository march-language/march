let strip_underscore s =
  if String.length s > 0 && s.[0] = '_'
  then String.sub s 1 (String.length s - 1)
  else s

let cap_of_symbol sym = List.assoc_opt (strip_underscore sym) table

let all_caps =
  List.sort_uniq String.compare (List.map snd table)
